def blocked_ids():
    return frozenset(set(HELD) | set(PHOTO_PENDING))


def held_ids():
    return blocked_ids()


def sql_exclude(alias=None):
    blocked = blocked_ids()
    if not blocked:
        return ""
    prefix = "%s." % alias if alias else ""
    ids = ",".join(str(product_id) for product_id in sorted(blocked))
    return " AND %sproduct_id NOT IN (%s)" % (prefix, ids)


def is_held(product):
    if isinstance(product, dict):
        product = product.get("product_id")
    try:
        return int(product) in blocked_ids()
    except (TypeError, ValueError):
        return False


def display_name(product):
    if isinstance(product, dict):
        product_id = product.get("product_id")
        try:
            renamed = RENAMED.get(int(product_id))
        except (TypeError, ValueError):
            renamed = None
        return renamed[1] if renamed else product.get("product_name")
    try:
        renamed = RENAMED.get(int(product))
    except (TypeError, ValueError):
        renamed = None
    return renamed[1] if renamed else None


def scrub_text(text, product_id):
    """``text`` with the frame's former name replaced by its neutral one."""
    try:
        product_id = int(product_id)
    except (TypeError, ValueError):
        return text
    former = FORMER_NAMES.get(product_id)
    formers = (former,) if isinstance(former, str) else tuple(former or ())
    renamed = RENAMED.get(product_id)
    if not text or not formers or not renamed:
        return text
    pattern = "|".join(re.escape(name) for name in
                       sorted(formers, key=len, reverse=True))
    return re.sub(r"(?<![A-Za-z0-9])(?:%s)(?![A-Za-z0-9])" % pattern,
                  lambda _m: renamed[1], str(text), flags=re.I)


def slugify(name):
    text = unicodedata.normalize("NFKD", str(name or ""))
    text = text.encode("ascii", "ignore").decode("ascii")
    text = re.sub(r"[^\w\s-]", "", text).strip().lower()
    return re.sub(r"[\s_-]+", "-", text)
