DETAILS = ("12 MP ultra-wide camera for hands-free photos and up to 3K video. Open-ear speakers for music, "
           "podcasts and calls. Built-in Meta AI: just say \"Hey Meta\". Up to 8 hours battery, with charging case. "
           "Pairs with the Meta AI app on Android and iOS. Genuine product; brand names and trademarks belong "
           "to their respective owners.")


def q(v):
    if v is None:
        return "NULL"
    if isinstance(v, (int, float)):
        return str(v)
    return "'" + str(v).replace("\\", "\\\\").replace("'", "''") + "'"


def main():
    out = ["-- AI Glasses import for optiwar.in (generated by build_import.py; review before applying)",
           "-- 10 Ray-Ban Meta Wayfarer (Gen 2) products: sell_on_in=1, sell_on_com=0, show_in_listings=0,",
           "-- quantity 999 (never reduced), HSN 85176290, sales_status PREORDER. Safe to re-run.",
           "SET NAMES utf8mb4;", ""]
    for sku, ean, style, frame, lens, size, lw, br, tl, mrp, sort in ROWS:
        code = sku.replace("/", "-")
        name = "Ray-Ban Meta Wayfarer Gen 2 %s%s / %s" % ("Large " if size == "Large" else "", frame, lens)
        slug = "ray-ban-meta-wayfarer-gen-2-%s-%s-%s" % (frame.lower().replace(" ", "-"),
                                                         lens.lower().replace(" ", "-"), size.lower())
        offer = int(round(mrp * (100 - OFFER_PCT) / 100.0))
        imgs = ",".join("./catalog/rayban-meta/%s/%s_%d.png" % (code, code, i) for i in (1, 2))
        seo = "Buy %s in India. Size %s (%s-%s-%s). Prescription lenses available." % (name, size, lw, br, tl)
        assert len(code) <= 20 and len(name) <= 100, (code, name)
        out.append("INSERT INTO products (product_code, product_name, product_details, product_price, "
                   "product_special_price, product_category, product_color, product_size, product_bridge, "
                   "product_lenght, product_image, product_quantity, hsn, product_slug, description_seo, "
                   "product_status, product_vertical, sell_on_com, sell_on_in, show_in_listings, product_vendor_code, "
                   "product_gender, product_type) SELECT %s FROM DUAL WHERE NOT EXISTS "
                   "(SELECT 1 FROM products WHERE product_code = %s);" % (", ".join(q(v) for v in (
                       code, name, DETAILS, mrp, offer, "AI Glasses", frame, "%s-%s-%s" % (lw, br, tl), br, tl, imgs, 999,
                       "85176290", slug, seo, "ACTIVE", "SMART_EYEWEAR", 0, 1, 0, sku, "Unisex", "AI Glasses")), q(code)))
        out.append("UPDATE products SET product_name=%s, product_details=%s, product_price=%s, "
                   "product_special_price=%s, product_image=%s, product_size=%s, product_quantity=999, hsn='85176290', "
                   "product_slug=%s, description_seo=%s, product_vertical='SMART_EYEWEAR', sell_on_com=0, "
                   "sell_on_in=1, show_in_listings=0 WHERE product_code=%s;"
                   % (q(name), q(DETAILS), mrp, offer, q(imgs), q("%s-%s-%s" % (lw, br, tl)), q(slug), q(seo), q(code)))
        out.append("INSERT INTO ai_glasses_products (product_id, family, family_title, style_code, frame_colour, "
                   "lens_colour, size_label, size_spec, brand, mpn, gtin, rx_allowed, rx_total_min, rx_total_max, "
                   "sales_status, sort_order) SELECT product_id, %s FROM products WHERE product_code=%s "
                   "ON DUPLICATE KEY UPDATE family=VALUES(family), family_title=VALUES(family_title), "
                   "style_code=VALUES(style_code), frame_colour=VALUES(frame_colour), lens_colour=VALUES(lens_colour), "
                   "size_label=VALUES(size_label), size_spec=VALUES(size_spec), brand=VALUES(brand), mpn=VALUES(mpn), "
                   "gtin=VALUES(gtin), rx_allowed=VALUES(rx_allowed), rx_total_min=VALUES(rx_total_min), "
                   "rx_total_max=VALUES(rx_total_max), sort_order=VALUES(sort_order);"
                   % (", ".join(q(v) for v in (FAMILY, FAMILY_TITLE, style, frame, lens, size, "%s-%s-%s" % (lw, br, tl),
                                               BRAND, sku, ean, 1, RX_TOTAL[0], RX_TOTAL[1], "PREORDER", sort)), q(code)))
        out.append("")
    out.append("INSERT INTO tax_tables (tax_slab, hsn) SELECT 18, '85176290' FROM DUAL "
               "WHERE NOT EXISTS (SELECT 1 FROM tax_tables WHERE hsn = '85176290');")
    out.append("INSERT INTO tax_tables (tax_slab, hsn) SELECT 5, '90015000' FROM DUAL "
               "WHERE NOT EXISTS (SELECT 1 FROM tax_tables WHERE hsn = '90015000');")
    with open(os.path.join(HERE, "ai_glasses_import.sql"), "w") as fh:
        fh.write("\n".join(out) + "\n")
    print("wrote %d products" % len(ROWS))


if __name__ == "__main__":
    main()
