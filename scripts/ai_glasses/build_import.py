    ("0RW4012601SSB53", "8056262721407", "clr", "Matte Black", "Clear", "Large", 53, 22, 155, 39900, 6),
    ("0RW4012601/7153", "8056262721346", "g15", "Shiny Black", "G15 Green", "Large", 53, 22, 155, 39900, 7),
    ("0RW4012601ST353", "8056262721421", "pgg", "Matte Black", "Polar Gradient Graphite", "Large", 53, 22, 155, 42100, 8),
    ("0RW4012601/1M53", "8056262721308", "tgg", "Shiny Black", "Transitions Graphite Green", "Large", 53, 22, 155, 45700, 9),
    ("0RW4012601S1Z53", "8056262721384", "tgy", "Matte Black", "Transitions Grey", "Large", 53, 22, 155, 45700, 10),
